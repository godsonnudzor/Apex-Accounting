alter table public.journal_entries
  add constraint journal_entries_source_check
  check (source in (
    'manual',
    'cheque',
    'cash',
    'bank_transfer',
    'payroll',
    'invoice',
    'supplier_bill',
    'supplier_credit',
    'receipt',
    'supplier_payment'
  ));

alter table public.payment_records
  add column if not exists settlement_type varchar(20)
  check (settlement_type in ('receipt', 'supplier_payment')),
  add column if not exists customer_id bigint
  references public.customers(id) on delete restrict,
  add column if not exists supplier_id bigint
  references public.suppliers(id) on delete restrict,
  add column if not exists currency varchar(10) not null default 'GHS';

do $$
declare
  v_code text;
  v_suffix integer;
begin
  insert into public.ledger_groups (name, account_type)
  values ('Account Payable', 'liability')
  on conflict (name) do nothing;

  if not exists (
    select 1
    from public.ledger_accounts
    where account_type = 'liability'
      and group_ledger = 'Account Payable'
  ) then
    v_suffix := 0;
    loop
      v_code := case when v_suffix = 0 then 'AP' else 'AP-' || v_suffix end;
      begin
        insert into public.ledger_accounts (code, name, account_type, group_ledger)
        values (v_code, 'Accounts Payable', 'liability', 'Account Payable');
        exit;
      exception when unique_violation then
        v_suffix := v_suffix + 1;
      end;
    end loop;
  end if;

  if not exists (
    select 1
    from public.ledger_accounts
    where code = 'EXP-UNCLASSIFIED'
  ) then
    v_suffix := 0;
    loop
      v_code := case
        when v_suffix = 0 then 'EXP-UNCLASSIFIED'
        else 'EXP-UNCLASSIFIED-' || v_suffix
      end;
      begin
        insert into public.ledger_accounts (code, name, account_type)
        values (v_code, 'Unclassified supplier expense', 'expense');
        exit;
      exception when unique_violation then
        v_suffix := v_suffix + 1;
      end;
    end loop;
  end if;
end;
$$;

create table if not exists public.payment_allocations (
  id bigint generated by default as identity primary key,
  payment_record_id bigint not null
    references public.payment_records(id) on delete cascade,
  customer_invoice_id bigint
    references public.customer_invoices(id) on delete restrict,
  supplier_bill_id bigint
    references public.supplier_bills(id) on delete restrict,
  amount numeric(14, 2) not null check (amount > 0),
  created_at timestamptz not null default now(),
  constraint payment_allocations_single_document_check
    check (num_nonnulls(customer_invoice_id, supplier_bill_id) = 1),
  constraint payment_allocations_unique_document
    unique (payment_record_id, customer_invoice_id, supplier_bill_id)
);

create index if not exists payment_allocations_invoice_idx
  on public.payment_allocations(customer_invoice_id);

create index if not exists payment_allocations_bill_idx
  on public.payment_allocations(supplier_bill_id);

create or replace function public.post_supplier_bill_journal(
  p_supplier_bill_id bigint,
  p_created_by bigint
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_bill public.supplier_bills%rowtype;
  v_existing_entry_id bigint;
  v_entry_id bigint;
  v_payable_account record;
  v_unclassified_account record;
  v_line record;
begin
  select *
    into v_bill
    from public.supplier_bills
   where id = p_supplier_bill_id
   for update;
  if not found then
    raise exception 'Supplier transaction not found';
  end if;

  select id
    into v_existing_entry_id
    from public.journal_entries
   where supplier_bill_id = p_supplier_bill_id;
  if v_existing_entry_id is not null then
    return v_existing_entry_id;
  end if;

  select id, code, name
    into v_payable_account
    from public.ledger_accounts
   where account_type = 'liability'
     and group_ledger = 'Account Payable'
     and is_active = true
   order by id
   limit 1;
  if not found then
    raise exception 'An active Accounts Payable ledger account is required';
  end if;

  select code, name
    into v_unclassified_account
    from public.ledger_accounts
   where code = 'EXP-UNCLASSIFIED'
      or name = 'Unclassified supplier expense'
   order by id
   limit 1;
  if not found then
    raise exception 'Unclassified supplier expense ledger account is required';
  end if;

  insert into public.journal_entries (
    entry_date,
    reference,
    description,
    source,
    status,
    supplier_bill_id,
    created_by
  )
  values (
    v_bill.bill_date,
    v_bill.reference,
    case
      when v_bill.document_type = 'credit' then 'Supplier credit'
      else 'Supplier bill'
    end || coalesce(' ' || nullif(v_bill.reference, ''), ''),
    case
      when v_bill.document_type = 'credit' then 'supplier_credit'
      else 'supplier_bill'
    end,
    'posted',
    v_bill.id,
    p_created_by
  )
  returning id into v_entry_id;

  for v_line in
    select
      line.amount,
      coalesce(account.code, v_unclassified_account.code) as account_code,
      coalesce(account.name, v_unclassified_account.name) as account_name
    from public.supplier_bill_lines as line
    left join public.ledger_accounts as account
      on account.id = line.ledger_account_id
   where line.supplier_bill_id = v_bill.id
  loop
    insert into public.journal_lines (
      journal_entry_id, account, debit, credit, memo
    )
    values (
      v_entry_id,
      v_line.account_code || ' - ' || v_line.account_name,
      case when v_bill.document_type = 'credit' then 0 else v_line.amount end,
      case when v_bill.document_type = 'credit' then v_line.amount else 0 end,
      coalesce(v_bill.memo, 'Supplier transaction expense')
    );
  end loop;

  if v_bill.tax_amount > 0 then
    insert into public.journal_lines (
      journal_entry_id, account, debit, credit, memo
    )
    values (
      v_entry_id,
      v_unclassified_account.code || ' - ' || v_unclassified_account.name,
      case when v_bill.document_type = 'credit' then 0 else v_bill.tax_amount end,
      case when v_bill.document_type = 'credit' then v_bill.tax_amount else 0 end,
      'Supplier transaction tax'
    );
  end if;

  if v_bill.discount_amount > 0 then
    insert into public.journal_lines (
      journal_entry_id, account, debit, credit, memo
    )
    values (
      v_entry_id,
      v_unclassified_account.code || ' - ' || v_unclassified_account.name,
      case when v_bill.document_type = 'credit' then v_bill.discount_amount else 0 end,
      case when v_bill.document_type = 'credit' then 0 else v_bill.discount_amount end,
      'Supplier transaction discount'
    );
  end if;

  insert into public.journal_lines (
    journal_entry_id, account, debit, credit, memo
  )
  values (
    v_entry_id,
    v_payable_account.code || ' - ' || v_payable_account.name,
    case when v_bill.document_type = 'credit' then v_bill.total_amount else 0 end,
    case when v_bill.document_type = 'credit' then 0 else v_bill.total_amount end,
    case
      when v_bill.document_type = 'credit' then 'Supplier credit payable'
      else 'Supplier bill payable'
    end
  );

  return v_entry_id;
end;
$$;

do $$
declare
  v_bill record;
begin
  for v_bill in
    select id
      from public.supplier_bills
     order by bill_date, id
  loop
    perform public.post_supplier_bill_journal(v_bill.id, null);
  end loop;
end;
$$;

create or replace function public.create_document_settlement(
  p_settlement_type varchar,
  p_party_id bigint,
  p_settlement_date date,
  p_payment_type varchar,
  p_reference varchar,
  p_cash_bank_account_id bigint,
  p_memo text,
  p_allocations jsonb,
  p_created_by bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_cash record;
  v_party record;
  v_document record;
  v_allocation record;
  v_payable record;
  v_invoice record;
  v_payment_id bigint;
  v_entry_id bigint;
  v_total numeric(14, 2) := 0;
  v_paid numeric(14, 2);
  v_available numeric(14, 2);
  v_credit_remaining numeric(14, 2);
  v_credit_offset numeric(14, 2);
  v_party_id bigint;
  v_currency varchar(10);
  v_seen integer := 0;
  v_processed integer := 0;
  v_account record;
begin
  if p_settlement_type not in ('receipt', 'supplier_payment') then
    raise exception 'Settlement type must be receipt or supplier payment';
  end if;
  if p_payment_type not in ('cheque', 'cash', 'bank_transfer') then
    raise exception 'Select cash, cheque, or bank transfer';
  end if;
  if p_settlement_date is null then
    raise exception 'Settlement date is required';
  end if;
  if p_party_id is null or p_party_id <= 0 then
    raise exception 'Select a valid customer or supplier';
  end if;
  if jsonb_typeof(p_allocations) <> 'array'
     or jsonb_array_length(p_allocations) = 0 then
    raise exception 'Select at least one outstanding transaction';
  end if;

  select
    cash.id,
    cash.account_name,
    upper(cash.currency) as currency,
    account.code,
    account.name,
    account.account_type,
    account.is_active
  into v_cash
  from public.cash_bank_accounts as cash
  join public.ledger_accounts as account
    on account.id = cash.ledger_account_id
  where cash.id = p_cash_bank_account_id
    and cash.is_active = true
  for update of cash;
  if not found
     or v_cash.account_type <> 'asset'
     or v_cash.is_active <> true then
    raise exception 'Select an active cash or bank asset account';
  end if;

  select count(*), count(distinct (item->>'documentId')::bigint)
    into v_seen, v_processed
    from jsonb_array_elements(p_allocations) as item;
  if v_seen <> v_processed then
    raise exception 'A transaction can only be selected once';
  end if;

  if p_settlement_type = 'receipt' then
    select id, name
      into v_party
      from public.customers
     where id = p_party_id;
    if not found then
      raise exception 'Customer not found';
    end if;
    v_party_id := p_party_id;
    v_currency := v_cash.currency;

    for v_allocation in
      select
        (item->>'documentId')::bigint as document_id,
        round((item->>'amount')::numeric, 2) as amount
      from jsonb_array_elements(p_allocations) as item
    loop
      if v_allocation.amount <= 0 then
        raise exception 'Every receipt allocation must be greater than zero';
      end if;
      select *
        into v_invoice
        from public.customer_invoices
       where id = v_allocation.document_id
         and customer_id = p_party_id
         and status = 'open'
       for update;
      if not found then
        raise exception 'A selected customer invoice is no longer open';
      end if;
      if upper(v_invoice.currency) <> v_currency then
        raise exception 'Receipt and invoice currencies must match';
      end if;
      select coalesce(sum(allocation.amount), 0)
        into v_paid
        from public.payment_allocations as allocation
        join public.payment_records as payment
          on payment.id = allocation.payment_record_id
       where allocation.customer_invoice_id = v_invoice.id
         and payment.settlement_type = 'receipt';
      v_available := round(v_invoice.total_amount - v_paid, 2);
      if v_allocation.amount > v_available then
        raise exception 'Receipt exceeds the remaining invoice balance';
      end if;
      select id, code, name, account_type, is_active
        into v_account
        from public.ledger_accounts
       where id = v_invoice.receivable_account_id;
      if not found
         or v_account.account_type <> 'asset'
         or v_account.is_active <> true then
        raise exception 'Invoice receivable account is not an active asset';
      end if;
      v_total := v_total + v_allocation.amount;
    end loop;
  else
    select id, name
      into v_party
      from public.suppliers
     where id = p_party_id;
    if not found then
      raise exception 'Supplier not found';
    end if;
    v_party_id := p_party_id;
    v_currency := v_cash.currency;

    for v_allocation in
      select
        (item->>'documentId')::bigint as document_id,
        round((item->>'amount')::numeric, 2) as amount
      from jsonb_array_elements(p_allocations) as item
    loop
      if v_allocation.amount <= 0 then
        raise exception 'Every payment allocation must be greater than zero';
      end if;
      select id, supplier_id, currency, document_type
        into v_document
        from public.supplier_bills
       where id = v_allocation.document_id
       for update;
      if not found
         or v_document.supplier_id <> p_party_id
         or v_document.document_type <> 'bill' then
        raise exception 'A selected supplier bill is no longer payable';
      end if;
      if upper(v_document.currency) <> v_currency then
        raise exception 'Payment and bill currencies must match';
      end if;
    end loop;

    select id, code, name
      into v_payable
      from public.ledger_accounts
     where account_type = 'liability'
       and group_ledger = 'Account Payable'
       and is_active = true
     order by id
     limit 1;
    if not found then
      raise exception 'An active Accounts Payable ledger account is required';
    end if;

    select coalesce(sum(total_amount), 0)
      into v_credit_remaining
      from public.supplier_bills
     where supplier_id = p_party_id
       and upper(currency) = v_currency
       and document_type = 'credit';

    for v_document in
      select id, total_amount
        from public.supplier_bills
       where supplier_id = p_party_id
         and upper(currency) = v_currency
         and document_type = 'bill'
       order by bill_date, id
       for update
    loop
      select coalesce(sum(allocation.amount), 0)
        into v_paid
        from public.payment_allocations as allocation
        join public.payment_records as payment
          on payment.id = allocation.payment_record_id
       where allocation.supplier_bill_id = v_document.id
         and payment.settlement_type = 'supplier_payment';
      v_available := greatest(round(v_document.total_amount - v_paid, 2), 0);
      v_credit_offset := least(v_available, v_credit_remaining);
      v_available := round(v_available - v_credit_offset, 2);
      v_credit_remaining := round(v_credit_remaining - v_credit_offset, 2);

      select round((item->>'amount')::numeric, 2)
        into v_allocation
        from jsonb_array_elements(p_allocations) as item
       where (item->>'documentId')::bigint = v_document.id;
      if found then
        if v_allocation.amount <= 0 or v_allocation.amount > v_available then
          raise exception 'Payment exceeds the remaining bill balance after credits';
        end if;
        v_total := v_total + v_allocation.amount;
        v_processed := v_processed - 1;
      end if;
    end loop;
    if v_processed <> 0 then
      raise exception 'A selected supplier bill is no longer payable';
    end if;
  end if;

  if v_total <= 0 then
    raise exception 'Settlement total must be greater than zero';
  end if;

  insert into public.journal_entries (
    entry_date, reference, description, source, status, created_by
  )
  values (
    p_settlement_date,
    nullif(trim(p_reference), ''),
    case
      when p_settlement_type = 'receipt'
        then 'Receipt from ' || v_party.name
      else 'Payment to ' || v_party.name
    end,
    p_settlement_type,
    'posted',
    p_created_by
  )
  returning id into v_entry_id;

  insert into public.payment_records (
    journal_entry_id,
    payment_type,
    payment_number,
    payment_date,
    payee,
    bank_account,
    cash_bank_account_id,
    amount,
    memo,
    created_by,
    settlement_type,
    customer_id,
    supplier_id,
    currency
  )
  values (
    v_entry_id,
    p_payment_type,
    nullif(trim(p_reference), ''),
    p_settlement_date,
    v_party.name,
    v_cash.code || ' - ' || v_cash.name,
    v_cash.id,
    v_total,
    nullif(trim(p_memo), ''),
    p_created_by,
    p_settlement_type,
    case when p_settlement_type = 'receipt' then v_party_id else null end,
    case when p_settlement_type = 'supplier_payment' then v_party_id else null end,
    v_currency
  )
  returning id into v_payment_id;

  if p_settlement_type = 'receipt' then
    insert into public.journal_lines (
      journal_entry_id, account, debit, credit, memo
    )
    values (
      v_entry_id,
      v_cash.code || ' - ' || v_cash.name,
      v_total,
      0,
      coalesce(nullif(trim(p_memo), ''), 'Customer receipt')
    );

    for v_allocation in
      select
        (item->>'documentId')::bigint as document_id,
        round((item->>'amount')::numeric, 2) as amount
      from jsonb_array_elements(p_allocations) as item
    loop
      select invoice.receivable_account_id, invoice.invoice_number,
             account.code, account.name
        into v_invoice
        from public.customer_invoices as invoice
        join public.ledger_accounts as account
          on account.id = invoice.receivable_account_id
       where invoice.id = v_allocation.document_id;
      insert into public.journal_lines (
        journal_entry_id, account, debit, credit, memo
      )
      values (
        v_entry_id,
        v_invoice.code || ' - ' || v_invoice.name,
        0,
        v_allocation.amount,
        'Receipt for invoice ' || v_invoice.invoice_number
      );

      insert into public.payment_allocations (
        payment_record_id, customer_invoice_id, amount
      )
      values (v_payment_id, v_allocation.document_id, v_allocation.amount);
    end loop;

    update public.customer_invoices as invoice
       set status = 'paid',
           updated_at = now()
     where invoice.status = 'open'
       and invoice.id in (
         select allocation.customer_invoice_id
           from public.payment_allocations as allocation
          where allocation.payment_record_id = v_payment_id
       )
       and invoice.total_amount <= (
         select coalesce(sum(allocation.amount), 0)
           from public.payment_allocations as allocation
           join public.payment_records as payment
             on payment.id = allocation.payment_record_id
          where allocation.customer_invoice_id = invoice.id
            and payment.settlement_type = 'receipt'
       );
  else
    insert into public.journal_lines (
      journal_entry_id, account, debit, credit, memo
    )
    values (
      v_entry_id,
      v_payable.code || ' - ' || v_payable.name,
      v_total,
      0,
      coalesce(nullif(trim(p_memo), ''), 'Supplier bill payment')
    );
    insert into public.journal_lines (
      journal_entry_id, account, debit, credit, memo
    )
    values (
      v_entry_id,
      v_cash.code || ' - ' || v_cash.name,
      0,
      v_total,
      coalesce(nullif(trim(p_memo), ''), 'Supplier bill payment')
    );

    for v_allocation in
      select
        (item->>'documentId')::bigint as document_id,
        round((item->>'amount')::numeric, 2) as amount
      from jsonb_array_elements(p_allocations) as item
    loop
      insert into public.payment_allocations (
        payment_record_id, supplier_bill_id, amount
      )
      values (v_payment_id, v_allocation.document_id, v_allocation.amount);
    end loop;
  end if;

  return jsonb_build_object(
    'paymentId', v_payment_id,
    'entryId', v_entry_id,
    'amount', v_total,
    'currency', v_currency
  );
end;
$$;

