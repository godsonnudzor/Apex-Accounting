  v_entry public.journal_entries%rowtype;
  v_previous jsonb;
  v_next jsonb;
begin
  select *
    into v_entry
    from public.journal_entries
   where id = p_entry_id
   for update;

  if not found then
    raise exception 'Journal entry not found';
  end if;
  if v_entry.source <> 'manual' or v_entry.status <> 'posted' then
    raise exception 'Only posted manual journal entries can be voided';
  end if;

  select jsonb_build_object(
    'entryDate', entry.entry_date,
    'reference', entry.reference,
    'description', entry.description,
    'status', entry.status,
    'debitTotal', coalesce(sum(line.debit), 0),
