create table if not exists public.accounting_audit_trail (
  id bigint generated by default as identity primary key,
  actor_user_id bigint references public.users(id) on delete set null,
  actor_name text not null,
  action text not null check (action in ('updated', 'voided')),
  entry_id bigint not null,
  page text not null,
  previous_values jsonb not null,
  new_values jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists accounting_audit_trail_created_at_idx
  on public.accounting_audit_trail(created_at desc);

alter table public.accounting_audit_trail enable row level security;
revoke all on public.accounting_audit_trail from public, anon, authenticated;
grant select on public.accounting_audit_trail to service_role;

create or replace function public.update_manual_journal_entry(
  p_entry_id bigint,
  p_entry_date date,
  p_reference text,
  p_description text,
  p_lines jsonb,
  p_actor_id bigint,
  p_actor_name text,
  p_page text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_entry public.journal_entries%rowtype;
  v_previous jsonb;
  v_next jsonb;
  v_debits numeric;
  v_credits numeric;
begin
  select *
    into v_entry
    from public.journal_entries
   where id = p_entry_id
   for update;

  if not found then
    raise exception 'Journal entry not found';
  end if;
  if v_entry.source <> 'manual' or v_entry.status <> 'posted' then
    raise exception 'Only posted manual journal entries can be edited';
  end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array'
     or jsonb_array_length(p_lines) < 2 then
    raise exception 'At least two journal lines are required';
  end if;

  select coalesce(sum((line->>'debit')::numeric), 0),
         coalesce(sum((line->>'credit')::numeric), 0)
    into v_debits, v_credits
    from jsonb_array_elements(p_lines) as line;

  if abs(v_debits - v_credits) > 0.005 then
    raise exception 'Journal debits and credits must balance';
  end if;

  select jsonb_build_object(
    'entryDate', entry.entry_date,
    'reference', entry.reference,
    'description', entry.description,
    'debitTotal', coalesce(sum(line.debit), 0),
    'creditTotal', coalesce(sum(line.credit), 0),
    'lines', coalesce(
      jsonb_agg(jsonb_build_object(
        'account', line.account,
        'debit', line.debit,
        'credit', line.credit,
        'memo', line.memo,
        'supplier_id', line.supplier_id,
        'customer_id', line.customer_id,
        'employee_id', line.employee_id
      ) order by line.id) filter (where line.id is not null),
      '[]'::jsonb
    )
  )
    into v_previous
    from public.journal_entries as entry
    left join public.journal_lines as line on line.journal_entry_id = entry.id
   where entry.id = p_entry_id
   group by entry.id;

  update public.journal_entries
     set entry_date = p_entry_date,
         reference = nullif(trim(p_reference), ''),
         description = trim(p_description)
   where id = p_entry_id;

  delete from public.journal_lines where journal_entry_id = p_entry_id;
  insert into public.journal_lines (
    journal_entry_id,
    account,
    debit,
    credit,
    memo,
    supplier_id,
    customer_id,
    employee_id
  )
  select p_entry_id,
         line.account,
         line.debit,
         line.credit,
         nullif(trim(line.memo), ''),
         line.supplier_id,
         line.customer_id,
         line.employee_id
    from jsonb_to_recordset(p_lines) as line(
      account text,
      debit numeric,
      credit numeric,
      memo text,
      supplier_id bigint,
      customer_id bigint,
      employee_id bigint
    );

  select jsonb_build_object(
    'entryDate', entry.entry_date,
    'reference', entry.reference,
    'description', entry.description,
    'debitTotal', coalesce(sum(line.debit), 0),
    'creditTotal', coalesce(sum(line.credit), 0),
    'lines', coalesce(
      jsonb_agg(jsonb_build_object(
        'account', line.account,
        'debit', line.debit,
        'credit', line.credit,
        'memo', line.memo,
        'supplier_id', line.supplier_id,
        'customer_id', line.customer_id,
        'employee_id', line.employee_id
      ) order by line.id) filter (where line.id is not null),
      '[]'::jsonb
    )
  )
    into v_next
    from public.journal_entries as entry
    left join public.journal_lines as line on line.journal_entry_id = entry.id
   where entry.id = p_entry_id
   group by entry.id;

  insert into public.accounting_audit_trail (
    actor_user_id,
    actor_name,
    action,
    entry_id,
    page,
    previous_values,
    new_values
  )
  values (
    p_actor_id,
    coalesce(nullif(trim(p_actor_name), ''), 'Unknown user'),
    'updated',
    p_entry_id,
    coalesce(nullif(trim(p_page), ''), 'Ledger report'),
    v_previous,
    v_next
  );
end;
$$;

create or replace function public.void_manual_journal_entry(
  p_entry_id bigint,
  p_actor_id bigint,
  p_actor_name text,
  p_page text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
