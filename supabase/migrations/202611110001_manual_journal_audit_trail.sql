    from public.journal_entries as entry
    left join public.journal_lines as line on line.journal_entry_id = entry.id
   where entry.id = p_entry_id
   group by entry.id;

  update public.journal_entries set status = 'void' where id = p_entry_id;

  select jsonb_build_object(
    'entryDate', entry.entry_date,
    'reference', entry.reference,
    'description', entry.description,
    'status', entry.status,
    'debitTotal', coalesce(sum(line.debit), 0),
    'creditTotal', coalesce(sum(line.credit), 0),
    'lines', coalesce(
      jsonb_agg(jsonb_build_object(
        'account', line.account,
